-- Contador de instalaciones: SECURITY DEFINER para poder incrementar el contador
-- de una extensión ajena sin que el RLS lo bloquee (el IDE llama a este RPC).
DROP FUNCTION IF EXISTS increment_installs(TEXT);
CREATE OR REPLACE FUNCTION increment_installs(p_ext_id TEXT)
RETURNS void
LANGUAGE sql SECURITY DEFINER
AS $$
    UPDATE extensions SET installs = COALESCE(installs, 0) + 1 WHERE ext_id = p_ext_id;
$$;

