-- 22. SISTEMA ANTI-FILTREO DE TABLAS EN EL INSPECTOR
-- ==========================================
CREATE OR REPLACE FUNCTION hide_tables_from_inspector()
RETURNS void AS $$
DECLARE
    tbl RECORD;
BEGIN
    FOR tbl IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND tablename IN (
        'project_api_config',
        'project_data',
        'hydra_api_keys',
        'project_auth_users',
        'project_auth_policies',
        'project_auth_providers',
        'project_storage_buckets',
        'project_storage_policies',
        'collab_files',
        'collab_members',
        'collab_groups',
        'collab_runs',
        'collab_presence',
        'tickets',
        'guild_config'
    ) LOOP
        EXECUTE format('COMMENT ON TABLE %I IS ''@hidden''', tbl.tablename);
    END LOOP;
END;
$$ LANGUAGE plpgsql;

SELECT hide_tables_from_inspector();

