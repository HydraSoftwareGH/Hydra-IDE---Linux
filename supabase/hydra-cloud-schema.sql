-- Email del usuario actual (del JWT de Firebase reenviado por el cliente).
CREATE OR REPLACE FUNCTION current_user_email()
RETURNS TEXT
LANGUAGE plpgsql SECURITY DEFINER STABLE
AS $$
BEGIN
    RETURN current_setting('request.jwt.claims', true)::json->>'email';
END;
$$;

-- ¿El usuario es admin?
CREATE OR REPLACE FUNCTION is_admin()
RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER STABLE
AS $$
BEGIN
    RETURN current_setting('request.jwt.claims', true)::json->>'role' = 'admin';
END;
$$;

-- ¿El usuario es miembro (o dueño) de un grupo de Hydra Team?
-- SECURITY DEFINER: consulta collab_members SIN aplicar su RLS -> evita la
-- recursión infinita que ocurre si la política de collab_members se consulta a
-- sí misma.
CREATE OR REPLACE FUNCTION is_group_member(gid BIGINT)
RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER STABLE
AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM collab_members
        WHERE collab_members.group_id = gid
          AND collab_members.user_email = current_setting('request.jwt.claims', true)::json->>'email'
    );
END;
$$;

-- ¿El usuario es miembro (o dueño) de un proyecto de Hydra Cloud?
CREATE OR REPLACE FUNCTION is_project_member(pid BIGINT)
RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER STABLE
AS $$
DECLARE
    uemail TEXT;
BEGIN
    uemail := current_setting('request.jwt.claims', true)::json->>'email';
    RETURN EXISTS (
        SELECT 1 FROM project_members
        WHERE project_members.project_id = pid
          AND project_members.user_email = uemail
    ) OR EXISTS (
        SELECT 1 FROM cloud_projects
        WHERE cloud_projects.id = pid
          AND cloud_projects.user_email = uemail
    );
END;
$$;

