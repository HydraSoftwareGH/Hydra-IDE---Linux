-- 1. cloud_projects
CREATE TABLE IF NOT EXISTS cloud_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    user_email TEXT NOT NULL,
    project_name TEXT NOT NULL,
    project_type TEXT NOT NULL,
    status TEXT DEFAULT 'active' CHECK (status IN ('active', 'suspended', 'deleted', 'provisioning')),
    region TEXT DEFAULT 'us-east-1',
    compute_size TEXT DEFAULT 'micro',
    storage_gb INTEGER DEFAULT 1,
    connection_string TEXT
);

-- 2. deployments
CREATE TABLE IF NOT EXISTS deployments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    project_id BIGINT REFERENCES cloud_projects(id) ON DELETE CASCADE,
    user_email TEXT NOT NULL,
    deployment_status TEXT DEFAULT 'pending' CHECK (deployment_status IN ('pending', 'running', 'success', 'failed')),
    commit_hash TEXT,
    logs TEXT
);

-- 3. project_tables
