-- Tabla de extensiones
CREATE TABLE IF NOT EXISTS extensions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ DEFAULT NOW(),
    updated_at      TIMESTAMPTZ DEFAULT NOW(),
    ext_id          TEXT UNIQUE NOT NULL,
    name            TEXT NOT NULL,
    description     TEXT NOT NULL DEFAULT '',
    readme          TEXT DEFAULT '',
    category        TEXT DEFAULT 'Otros',
    version         TEXT DEFAULT '1.0.0',
    icon_url        TEXT,
    code            TEXT DEFAULT '',
    author_user_id  TEXT,
    author_email    TEXT,
    author_username TEXT,
    installs        INTEGER DEFAULT 0,
    rating          NUMERIC DEFAULT 5,
    is_published    BOOLEAN DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_extensions_ext_id     ON extensions (ext_id);
CREATE INDEX IF NOT EXISTS idx_extensions_created_at ON extensions (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_extensions_installs   ON extensions (installs DESC);
CREATE INDEX IF NOT EXISTS idx_extensions_author     ON extensions (author_email);
CREATE INDEX IF NOT EXISTS idx_extensions_category   ON extensions (category);
CREATE INDEX IF NOT EXISTS idx_extensions_published  ON extensions (is_published);

-- Trigger updated_at automático (para la tabla de extensiones)
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_extensions_updated ON extensions;
CREATE TRIGGER trg_extensions_updated
    BEFORE UPDATE ON extensions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- RPC: contar instalaciones
CREATE OR REPLACE FUNCTION increment_installs(p_ext_id TEXT)
RETURNS void AS $$
BEGIN
    UPDATE extensions SET installs = installs + 1 WHERE ext_id = p_ext_id;
END;
$$ LANGUAGE plpgsql;

